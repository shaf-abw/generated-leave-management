CREATE TABLE employee (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(254) NOT NULL,
    role       VARCHAR(20)  NOT NULL,
    manager_id BIGINT REFERENCES employee (id),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT employee_role_check CHECK (role IN ('EMPLOYEE', 'MANAGER')),
    CONSTRAINT employee_not_own_manager_check CHECK (manager_id IS NULL OR manager_id <> id)
);

CREATE UNIQUE INDEX employee_email_lower_uk ON employee (lower(email));
CREATE INDEX employee_manager_idx ON employee (manager_id);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   BIGINT       NOT NULL UNIQUE REFERENCES employee (id),
    username      VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE leave_request (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id      BIGINT       NOT NULL REFERENCES employee (id),
    type             VARCHAR(20)  NOT NULL,
    start_date       DATE         NOT NULL,
    end_date         DATE         NOT NULL,
    reason           VARCHAR(500),
    status           VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    decided_by       BIGINT REFERENCES employee (id),
    decision_comment VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    decided_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT leave_request_type_check CHECK (type IN ('ANNUAL', 'SICK', 'UNPAID', 'OTHER')),
    CONSTRAINT leave_request_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT leave_request_dates_check CHECK (end_date >= start_date)
);

CREATE INDEX leave_request_employee_created_idx ON leave_request (employee_id, created_at DESC);
CREATE INDEX leave_request_status_idx ON leave_request (status);
